-- A client's review of a completed visit: a 1-5 rating, a comment and an optional photo, one per
-- appointment. A new table only, so the Worker-parity responses stay unchanged.

create table reviews (
  id integer generated by default as identity primary key,
  appointment_id integer not null unique references appointments (id) on delete cascade,
  user_id integer not null references users (id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  comment text not null default '',
  photo_url text,
  created_at text default clawholics_utc_now()
);
create index idx_reviews_user on reviews (user_id);

alter table reviews enable row level security;
