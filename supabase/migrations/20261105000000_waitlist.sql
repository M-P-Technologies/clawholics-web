-- The waitlist: a client who finds a day fully booked asks to be told if a time opens up on it, for
-- one artist or for any artist who does the service (nailist_id null). When a slot is released (a
-- cancellation, a hold that ran out, a reschedule) and the day has a time free again, each entry
-- waiting for it gets one email and notified_at is set. An entry ends when it's been emailed or its
-- day has passed.
create table waitlist_entries (
  id integer generated by default as identity primary key,
  user_id integer not null references users (id) on delete cascade,
  service_id integer not null references services (id) on delete cascade,
  nailist_id integer references nailists (id) on delete cascade,
  appointment_date text not null,
  created_at text default clawholics_utc_now(),
  notified_at text
);
-- One entry per client, service, artist (or "any") and day
create unique index idx_waitlist_unique on waitlist_entries (user_id, service_id, coalesce(nailist_id, 0), appointment_date);
create index idx_waitlist_waiting on waitlist_entries (appointment_date) where notified_at is null;
alter table waitlist_entries enable row level security;
