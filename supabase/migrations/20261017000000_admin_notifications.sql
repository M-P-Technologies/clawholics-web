-- The admins' notifications of new bookings (the bell in the admin top bar): a booking paid
-- online, or a payment proof uploaded for review. One row per event, shared by every admin; each
-- admin's "read" state is how far they've seen (admin_notification_seen), so marking read is one
-- upsert however many there are.

create table admin_notifications (
  id integer generated by default as identity primary key,
  -- 'booking_paid' (ref_id is the appointment) or 'proof_uploaded' (ref_id is the proof)
  kind text not null check (kind in ('booking_paid', 'proof_uploaded')),
  ref_id integer not null,
  appointment_id integer references appointments (id) on delete cascade,
  created_at text default clawholics_utc_now(),
  -- A repeated webhook or retried upload doesn't notify twice
  unique (kind, ref_id)
);

create table admin_notification_seen (
  user_id integer primary key references users (id) on delete cascade,
  last_seen_id integer not null default 0,
  updated_at text default clawholics_utc_now()
);

alter table admin_notifications enable row level security;
alter table admin_notification_seen enable row level security;
