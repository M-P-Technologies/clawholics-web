-- Photos of each artist's work, shown on the artist's page. Same shape as service_gallery.
create table nailist_gallery (
  id integer generated by default as identity primary key,
  nailist_id integer not null references nailists (id) on delete cascade,
  image_url text not null,
  position integer not null
);
create unique index idx_unique_nailist_gallery_item on nailist_gallery (nailist_id, image_url, position);

alter table nailist_gallery enable row level security;
