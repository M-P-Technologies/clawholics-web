-- The visit flow: the client's payment screenshot is asked for again by email once, and a
-- completed visit records what was paid at the salon and who did it.

-- When the "send your payment screenshot" reminder went out (once per booking; cleared again if
-- Resend refuses it, so the next run retries)
alter table appointments add column screenshot_reminder_sent_at text;

-- A completed visit: the balance the client paid at the salon (on top of the downpayment), how
-- they paid it (for the record), and the artist who actually did it. One per appointment.
create table visit_completions (
  id integer generated by default as identity primary key,
  appointment_id integer not null unique references appointments (id),
  balance_amount integer not null check (balance_amount >= 0),
  payment_method text not null,
  nailist_id integer not null references nailists (id),
  completed_by integer references users (id),
  created_at text default clawholics_utc_now(),
  updated_at text default clawholics_utc_now()
);
alter table visit_completions enable row level security;

-- The bell also says when a confirmed visit is over and waits to be completed
alter table admin_notifications drop constraint admin_notifications_kind_check;
alter table admin_notifications add constraint admin_notifications_kind_check
  check (kind in ('booking_paid', 'proof_uploaded', 'visit_to_complete'));
