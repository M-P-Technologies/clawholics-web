-- Private admin notes on a client, optionally about one of their appointments, and one
-- "next steps" text per client. New tables only, so the Worker-parity responses stay unchanged.

create table client_notes (
  id integer generated by default as identity primary key,
  client_user_id integer not null references users (id) on delete cascade,
  appointment_id integer references appointments (id) on delete cascade,
  author_admin_id integer references users (id) on delete set null,
  note text not null,
  created_at text default clawholics_utc_now(),
  updated_at text default clawholics_utc_now()
);
create index idx_client_notes_client on client_notes (client_user_id);

create table client_next_steps (
  client_user_id integer primary key references users (id) on delete cascade,
  text text not null default '',
  updated_by integer references users (id) on delete set null,
  updated_at text default clawholics_utc_now()
);

alter table client_notes enable row level security;
alter table client_next_steps enable row level security;
