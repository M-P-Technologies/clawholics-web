-- The options a client added to a booking: extras on top of the service's price (service_variants).
-- Kept with their name and price at booking time, so a later edit of the service doesn't change
-- what the visit costs. The deposit isn't affected; the Complete visit form adds them to the bill.
create table appointment_options (
  id integer generated by default as identity primary key,
  appointment_id integer not null references appointments (id) on delete cascade,
  variant_id integer references service_variants (id) on delete set null,
  name text not null,
  price integer not null check (price >= 0)
);
create index idx_appointment_options_appointment on appointment_options (appointment_id);
alter table appointment_options enable row level security;
