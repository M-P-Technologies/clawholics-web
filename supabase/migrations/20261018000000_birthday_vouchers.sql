-- Birthday vouchers: every client whose birthday (customer_profiles.dob) falls in this month gets
-- one voucher a year, valid for that month, issued and emailed by the daily cron
-- (GET /api/cron/birthday-vouchers). The client claims it from the pop-up or their profile; the
-- discount is on the service price paid at the salon, the downpayment is unchanged.

create table birthday_vouchers (
  id integer generated by default as identity primary key,
  user_id integer not null references users (id) on delete cascade,
  year integer not null,
  code text not null unique,
  discount_pct integer not null default 20 check (discount_pct between 1 and 100),
  -- The birthday month, first and last day (YYYY-MM-DD, Manila time)
  valid_from text not null,
  valid_until text not null,
  status text not null default 'ISSUED' check (status in ('ISSUED', 'CLAIMED', 'USED', 'EXPIRED')),
  claimed_at text,
  used_at text,
  -- Set when the email is handed to Resend, so a rerun of the cron doesn't send it again
  emailed_at text,
  created_at text default clawholics_utc_now(),
  -- One voucher per client per year
  unique (user_id, year)
);

alter table birthday_vouchers enable row level security;

insert into site_settings (key, value) values ('birthday_discount_pct', '20') on conflict (key) do nothing;
