-- A service's options (e.g. "Short" / "Long"), each with its own price, edited in Admin >
-- Services. The client picks one when booking; a service without any is priced by its tiers.
create table service_variants (
  id integer generated by default as identity primary key,
  service_id integer not null references services (id) on delete cascade,
  name text not null,
  price integer not null check (price > 0),
  position integer not null default 0
);
create index idx_service_variants_service on service_variants (service_id, position);
alter table service_variants enable row level security;
